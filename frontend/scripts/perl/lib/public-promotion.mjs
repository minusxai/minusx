import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
export const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
export function admitPublicPerlPromotion(lock, {run, jobs, artifact, workflow, verifier, qualificationLock, archive}) {
  assert.equal(lock.schema, 1);
  assert.equal(lock.mode, 'public-reviewed-source-reattestation');
  assert.match(lock.repository, /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/);
  for (const key of ['repository_id', 'run_id', 'run_attempt', 'job_id', 'artifact_id', 'artifact_size']) assert.ok(Number.isSafeInteger(lock[key]) && lock[key] > 0);
  assert.match(lock.head_sha, /^[a-f0-9]{40}$/);
  for (const key of ['workflow_sha256', 'verifier_sha256', 'qualification_lock_sha256', 'manifest_sha256', 'original_profile_sha256']) assert.match(lock[key], /^[a-f0-9]{64}$/);
  assert.match(lock.artifact_digest, /^sha256:[a-f0-9]{64}$/);
  assert.equal(lock.platform, 'linux/amd64');
  assert.equal(run.repository.full_name, lock.repository);
  assert.equal(run.repository.id, lock.repository_id);
  assert.equal(run.repository.private, false);
  assert.equal(run.head_repository.full_name, lock.repository);
  assert.equal(run.head_repository.id, lock.repository_id);
  assert.equal(run.head_repository.private, false);
  assert.equal(run.id, lock.run_id);
  assert.equal(run.run_attempt, lock.run_attempt);
  assert.equal(run.head_sha, lock.head_sha);
  assert.equal(run.path, lock.workflow_path);
  assert.equal(run.event, 'push');
  assert.equal(run.status, 'completed');
  assert.equal(run.conclusion, 'success');
  const selected = jobs.jobs.filter(job => job.id === lock.job_id);
  assert.equal(selected.length, 1);
  const job = selected[0];
  assert.equal(job.name, lock.job_name);
  assert.equal(job.head_sha, lock.head_sha);
  assert.equal(job.run_id, lock.run_id);
  assert.equal(job.run_attempt, lock.run_attempt);
  assert.equal(job.status, 'completed');
  assert.equal(job.conclusion, 'success');
  assert.equal(artifact.id, lock.artifact_id);
  assert.equal(artifact.name, lock.artifact_name);
  assert.equal(artifact.expired, false);
  assert.equal(artifact.workflow_run.id, lock.run_id);
  assert.equal(artifact.workflow_run.repository_id, lock.repository_id);
  assert.equal(artifact.workflow_run.head_repository_id, lock.repository_id);
  assert.equal(artifact.workflow_run.head_sha, lock.head_sha);
  assert.equal(artifact.digest, lock.artifact_digest);
  assert.equal(artifact.size_in_bytes, lock.artifact_size);
  assert.equal(archive.length, lock.artifact_size);
  assert.equal('sha256:' + sha256(archive), lock.artifact_digest);
  assert.equal(sha256(workflow), lock.workflow_sha256);
  assert.equal(sha256(verifier), lock.verifier_sha256);
  assert.equal(sha256(qualificationLock), lock.qualification_lock_sha256);
  const input = JSON.parse(qualificationLock);
  for (const key of ['manifest_sha256', 'original_profile_sha256', 'base_index', 'base_child', 'platform']) assert.equal(input[key], lock[key]);
  return {schema: 1, kind: 'authenticated-public-reviewed-perl-promotion', repository: lock.repository, run_id: lock.run_id, run_attempt: lock.run_attempt, source_head: lock.head_sha, workflow_sha256: lock.workflow_sha256, job_id: lock.job_id, artifact_id: lock.artifact_id, artifact_digest: lock.artifact_digest, manifest_sha256: lock.manifest_sha256, original_profile_sha256: lock.original_profile_sha256, base_index: lock.base_index, base_child: lock.base_child, platform: lock.platform, source_compiled_in_promotion: false, source_tests_rerun_in_promotion: false};
}
